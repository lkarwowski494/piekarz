HANDLOWE = {450: 'tortowa', 500: 'wrocławska', 550: 'luksusowa', 650: 'bułkowa', 750: 'chlebowa', 1850: 'graham'}

def nawias(jez, wnetrze):
    return f'（{wnetrze}）' if jez in ('ja', 'zh-Hant') else f' ({wnetrze})'

def typ(jez, n, handlowa=None):
    t = T[jez]
    sep = '、' if jez == 'ja' else '，' if jez == 'zh-Hant' else ', '
    pt = f"{t['PT']}{n}" if jez == 'ja' else f"{t['PT']} {n}"
    return pt + (sep + handlowa if handlowa else '')

def nazwa(jez, zboze, n):
    """Nazwa mąki (zboże: pszenna|żytnia|orkiszowa, n: numer typu) według D-307."""
    t = T[jez]
    if zboze == 'pszenna':
        baza = t['WW'] if n == 2000 else t['W']
        return baza + nawias(jez, typ(jez, n, HANDLOWE.get(n)))
    baza = t['R'] if zboze == 'żytnia' else t['S']
    return baza + nawias(jez, typ(jez, n))

